/** A slider on the Features → Hill tab, debug lines on by default. */
function hillSetting(
  id: string,
  name: string,
  min: number,
  max: number,
  step: number,
  value: number,
  unit: string,
): SliderSetting {
  return { kind: 'slider', id, name, tab: 'MAP', section: 'Features', subtab: 'Hill', min, max, step, default: value, unit, hasDebug: true, debugDefault: true }
}

/** A hill setting plus its indented Variation row (id + 'Var', ± %). */
function varied(
  id: string,
  name: string,
  min: number,
  max: number,
  step: number,
  value: number,
  unit: string,
  variation: number,
): SliderSetting[] {
  return [
    hillSetting(id, name, min, max, step, value, unit),
    { ...hillSetting(`${id}Var`, 'Variation', 0, 100, 5, variation, '%'), hasDebug: false, debugDefault: false, indent: true },
  ]
}

/** A slider on the BIKE tab. */
function bikeSetting(
  id: string,
  name: string,
  section: string,
  min: number,
  max: number,
  step: number,
  value: number,
  unit: string,
  debug: boolean,
): SliderSetting {
  return { kind: 'slider', id, name, tab: 'BIKE', section, min, max, step, default: value, unit, hasDebug: debug, debugDefault: debug }
}

/** A slider on the RIDER tab. */
function riderSetting(
  id: string,
  name: string,
  section: string,
  min: number,
  max: number,
  step: number,
  value: number,
  unit: string,
  debug: boolean,
): SliderSetting {
  return { ...bikeSetting(id, name, section, min, max, step, value, unit, debug), tab: 'RIDER' }
}

/** A rebindable key on the CONTROLS tab. */
function keySetting(id: string, name: string, section: string, code: string): KeySetting {
  return { kind: 'key', id, name, tab: 'CONTROLS', section, default: code, hasDebug: false, debugDefault: false }
}
